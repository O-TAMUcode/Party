function pickIcon(room, want) {
  const used = new Set([...room.members.values()].map(m => m.icon));
  if (ICONS.includes(want) && !used.has(want)) return want;
  return ICONS.find(i => !used.has(i));
}

function lobbyData(room) {
  return {
    t: 'lobby',
    code: room.code,
    started: room.started,
    members: [...room.members.values()]
      .map(m => ({ slot: m.slot, name: m.name, icon: m.icon, host: m.cid === room.hostCid }))
      .sort((a, b) => a.slot - b.slot),
  };
}

// ev.to: 'all' | 'others'(ホスト以外) | 'host' | スロット番号
function matches(room, ev, m) {
  const t = ev.to;
  return t === 'all' || (t === 'others' && m.cid !== room.hostCid) ||
    (t === 'host' && m.cid === room.hostCid) || t === m.slot;
}
function writeEv(res, ev) {
  try { res.write(`id: ${ev.id}\ndata: ${JSON.stringify(ev.data)}\n\n`); } catch (e) { /* closed */ }
}
function push(room, to, data) {
  const ev = { id: ++room.nextId, to, data };
  room.events.push(ev);
  if (room.events.length > 800) room.events.shift();
  for (const m of room.members.values()) if (m.res && matches(room, ev, m)) writeEv(m.res, ev);
  room.touched = Date.now();
  return ev;
}
const pushLobby = room => push(room, 'all', lobbyData(room));

function removeMember(room, cid) {
  const m = room.members.get(cid);
  if (!m) return;
  clearTimeout(m.timer);
  try { if (m.res) m.res.end(); } catch (e) { /* ignore */ }
  room.members.delete(cid);
  if (cid === room.hostCid) {
    push(room, 'all', { t: 'closed' });
    setTimeout(() => {
      for (const x of room.members.values()) { try { x.res && x.res.end(); } catch (e) { /* ignore */ } clearTimeout(x.timer); }
      rooms.delete(room.code);
    }, 600);
    room.closing = true;
  } else if (room.started) {
    push(room, 'host', { t: 'left', from: m.slot });
  } else {
    pushLobby(room);
  }
}

function sendJson(res, code, obj) {
  res.writeHead(code, { 'Content-Type': 'application/json; charset=utf-8', 'Cache-Control': 'no-store' });
  res.end(JSON.stringify(obj));
}
function readBody(req) {
  return new Promise(resolve => {
    let d = '';
    req.on('data', c => { d += c; if (d.length > 200000) req.destroy(); });
    req.on('end', () => { try { resolve(JSON.parse(d || '{}')); } catch (e) { resolve({}); } });
    req.on('error', () => resolve({}));
  });
}

function sse(req, res, u) {
  const room = rooms.get(String(u.searchParams.get('room')));
  const m = room && room.members.get(String(u.searchParams.get('cid')));
  if (!m) { res.writeHead(404); return res.end(); }
  res.writeHead(200, {
    'Content-Type': 'text/event-stream',
    'Cache-Control': 'no-cache, no-transform',
    'Connection': 'keep-alive',
    'X-Accel-Buffering': 'no',
  });
  res.write('retry: 1500\n\n');
  if (m.res && m.res !== res) { try { m.res.end(); } catch (e) { /* ignore */ } }
  m.res = res;
  clearTimeout(m.timer);
  const last = parseInt(req.headers['last-event-id'], 10);
  if (!isNaN(last)) {
    for (const ev of room.events) if (ev.id > last && matches(room, ev, m)) writeEv(res, ev);
  } else {
    writeEv(res, { id: room.nextId, data: lobbyData(room) });
  }
  req.on('close', () => {
    if (m.res === res) {
      m.res = null;
      m.timer = setTimeout(() => removeMember(room, m.cid), room.started ? 30000 : 8000);
    }
  });
}

