// パーティーアイランド オンライン対戦サーバー(依存パッケージなし / Node 18+)
// 役割: 部屋の管理 + ホストと参加者のメッセージ中継(SSE + POST)。ゲームの進行はホストの端末が行う。
const http = require('http');
const fs = require('fs');
const path = require('path');

const PORT = process.env.PORT || 3000;
const rooms = new Map();
const MAX_PLAYERS = 8;

const uid = () => Math.random().toString(36).slice(2, 10) + Date.now().toString(36);
function newCode() {
  let c;
  do { c = String(1000 + Math.floor(Math.random() * 9000)); } while (rooms.has(c));
  return c;
}
const cleanName = n => String(n || '').replace(/[<>&"'`]/g, '').trim().slice(0, 8) || 'ななし';
const ICONS = ['🐱','🐶','🐸','🐼','🐰','🦊','🐻','🐯','🦁','🐵','🐷','🐮','🐔','🐧','🐙','🦄','🐲','🐳','🦖','🐢','🐝','🦉','🐨','🐹'];
// 希望のアイコンが空いていればそれを、使用中なら空いている先頭のものを返す
function pickIcon(room, want) {
  const used = new Set([...room.members.values()].map(m => m.icon));
  if (ICONS.includes(want) && !used.has(want)) return want;
  return ICONS.find(i => !used.has(i));
}

function lobbyData(room) {
  return {
    t: 'lobby',
    code: room.code,
    started: room.started,
    members: [...room.members.values()]
      .map(m => ({ slot: m.slot, name: m.name, icon: m.icon, host: m.cid === room.hostCid }))
      .sort((a, b) => a.slot - b.slot),
  };
}

// ev.to: 'all' | 'others'(ホスト以外) | 'host' | スロット番号
function matches(room, ev, m) {
  const t = ev.to;
  return t === 'all' || (t === 'others' && m.cid !== room.hostCid) ||
    (t === 'host' && m.cid === room.hostCid) || t === m.slot;
}
function writeEv(res, ev) {
  try { res.write(`id: ${ev.id}\ndata: ${JSON.stringify(ev.data)}\n\n`); } catch (e) { /* closed */ }
}
function push(room, to, data) {
  const ev = { id: ++room.nextId, to, data };
  room.events.push(ev);
  if (room.events.length > 800) room.events.shift();
  for (const m of room.members.values()) if (m.res && matches(room, ev, m)) writeEv(m.res, ev);
  room.touched = Date.now();
  return ev;
}
const pushLobby = room => push(room, 'all', lobbyData(room));

function removeMember(room, cid) {
  const m = room.members.get(cid);
  if (!m) return;
  clearTimeout(m.timer);
  try { if (m.res) m.res.end(); } catch (e) { /* ignore */ }
  room.members.delete(cid);
  if (cid === room.hostCid) {
    push(room, 'all', { t: 'closed' });
    setTimeout(() => {
      for (const x of room.members.values()) { try { x.res && x.res.end(); } catch (e) { /* ignore */ } clearTimeout(x.timer); }
      rooms.delete(room.code);
    }, 600);
    room.closing = true;
  } else if (room.started) {
    push(room, 'host', { t: 'left', from: m.slot });
  } else {
    pushLobby(room);
  }
}

function sendJson(res, code, obj) {
  res.writeHead(code, { 'Content-Type': 'application/json; charset=utf-8', 'Cache-Control': 'no-store' });
  res.end(JSON.stringify(obj));
}
function readBody(req) {
  return new Promise(resolve => {
    let d = '';
    req.on('data', c => { d += c; if (d.length > 200000) req.destroy(); });
    req.on('end', () => { try { resolve(JSON.parse(d || '{}')); } catch (e) { resolve({}); } });
    req.on('error', () => resolve({}));
  });
}

function sse(req, res, u) {
  const room = rooms.get(String(u.searchParams.get('room')));
  const m = room && room.members.get(String(u.searchParams.get('cid')));
  if (!m) { res.writeHead(404); return res.end(); }
  res.writeHead(200, {
    'Content-Type': 'text/event-stream',
    'Cache-Control': 'no-cache, no-transform',
    'Connection': 'keep-alive',
    'X-Accel-Buffering': 'no',
  });
  res.write('retry: 1500\n\n');
  if (m.res && m.res !== res) { try { m.res.end(); } catch (e) { /* ignore */ } }
  m.res = res;
  clearTimeout(m.timer);
  const last = parseInt(req.headers['last-event-id'], 10);
  if (!isNaN(last)) {
    for (const ev of room.events) if (ev.id > last && matches(room, ev, m)) writeEv(res, ev);
  } else {
    writeEv(res, { id: room.nextId, data: lobbyData(room) });
  }
  req.on('close', () => {
    if (m.res === res) {
      m.res = null;
      m.timer = setTimeout(() => removeMember(room, m.cid), room.started ? 30000 : 8000);
    }
  });
}

const server = http.createServer(async (req, res) => {
  try {
    const u = new URL(req.url, 'http://localhost');
    if (req.method === 'GET' && (u.pathname === '/' || u.pathname === '/index.html')) {
      const html = HTML;
      res.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8', 'Cache-Control': 'no-cache' });
      return res.end(html);
    }
    if (u.pathname === '/healthz') { res.writeHead(200); return res.end('ok'); }
    if (req.method === 'GET' && u.pathname === '/api/events') return sse(req, res, u);

    if (req.method === 'POST') {
      const b = await readBody(req);

      if (u.pathname === '/api/create') {
        if (rooms.size >= 300) return sendJson(res, 200, { ok: false, err: 'busy' });
        const code = newCode();
        const cid = uid();
        const room = { code, hostCid: cid, members: new Map(), nextId: 0, events: [], started: false, touched: Date.now() };
        room.members.set(cid, { cid, name: cleanName(b.name), slot: 0, icon: pickIcon(room, b.icon), res: null, timer: null });
        rooms.set(code, room);
        return sendJson(res, 200, { ok: true, room: code, cid, slot: 0 });
      }

      if (u.pathname === '/api/join') {
        const room = rooms.get(String(b.room || '').trim());
        if (!room || room.closing) return sendJson(res, 200, { ok: false, err: 'room' });
        if (room.started) return sendJson(res, 200, { ok: false, err: 'started' });
        const used = new Set([...room.members.values()].map(m => m.slot));
        let slot = -1;
        for (let i = 0; i < MAX_PLAYERS; i++) if (!used.has(i)) { slot = i; break; }
        if (slot < 0) return sendJson(res, 200, { ok: false, err: 'full' });
        const cid = uid();
        room.members.set(cid, { cid, name: cleanName(b.name), slot, icon: pickIcon(room, b.icon), res: null, timer: null });
        // 接続されるまでに抜けた場合に備えて猶予タイマーを置く
        const m = room.members.get(cid);
        m.timer = setTimeout(() => removeMember(room, cid), 15000);
        pushLobby(room);
        return sendJson(res, 200, { ok: true, room: room.code, cid, slot });
      }

      if (u.pathname === '/api/send') {
        const room = rooms.get(String(b.room));
        const m = room && room.members.get(String(b.cid));
        if (!m) return sendJson(res, 200, { ok: false, err: 'room' });
        const msgs = Array.isArray(b.msgs) ? b.msgs.slice(0, 60) : [];
        if (m.cid === room.hostCid) {
          for (const msg of msgs) {
            if (!msg || typeof msg !== 'object') continue;
            const { to, ...data } = msg;
            const target = (typeof to === 'number' && to >= 0 && to < MAX_PLAYERS) ? to : 'others';
            if (data.t === 'begin') room.started = true;
            push(room, target, data);
          }
        } else {
          for (const msg of msgs) {
            if (!msg || (msg.t !== 'ans' && msg.t !== 'score')) continue;
            push(room, 'host', { ...msg, from: m.slot });
          }
        }
        return sendJson(res, 200, { ok: true });
      }

      if (u.pathname === '/api/icon') {
        const room = rooms.get(String(b.room));
        const m = room && room.members.get(String(b.cid));
        if (!m) return sendJson(res, 200, { ok: false, err: 'room' });
        const ic = String(b.icon);
        if (!ICONS.includes(ic) || [...room.members.values()].some(x => x !== m && x.icon === ic)) {
          return sendJson(res, 200, { ok: false, err: 'taken' });
        }
        m.icon = ic;
        if (!room.started) pushLobby(room);
        return sendJson(res, 200, { ok: true });
      }

      if (u.pathname === '/api/leave') {
        const room = rooms.get(String(b.room));
        if (room) removeMember(room, String(b.cid));
        return sendJson(res, 200, { ok: true });
      }
    }

    res.writeHead(404, { 'Content-Type': 'text/plain; charset=utf-8' });
    res.end('not found');
  } catch (e) {
    console.error(e);
    try { res.writeHead(500); res.end('error'); } catch (e2) { /* ignore */ }
  }
});
server.keepAliveTimeout = 65000;

// 接続を保つための ping と、古い部屋のお掃除
setInterval(() => {
  const now = Date.now();
  for (const [code, room] of rooms) {
    let alive = false;
    for (const m of room.members.values()) {
      if (m.res) { alive = true; try { m.res.write(': ping\n\n'); } catch (e) { /* ignore */ } }
    }
    if (!alive && now - room.touched > 5 * 60 * 1000) rooms.delete(code);
  }
}, 20000);

server.listen(PORT, '0.0.0.0', () => console.log('Party Island server on :' + PORT));
